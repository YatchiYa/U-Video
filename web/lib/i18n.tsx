export type Lang = "fr" | "en";
const DICTS: Record<Lang, Record<Key, string>> = { en, fr };
const STORAGE_KEY = "ugc.lang";

type Vars = Record<string, string | number>;
export type T = (key: Key, vars?: Vars) => string;

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: T;
  /** Translate a key built at runtime (e.g. "job.stage." + stage); falls back to `fallback`. */
  tx: (key: string, fallback?: string, vars?: Vars) => string;
}

function fill(s: string, vars?: Vars): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("fr");

  useEffect(() => {
    let saved: string | null = null;
    try {
      saved = localStorage.getItem(STORAGE_KEY);
    } catch {
      /* storage blocked: keep the default */
    }
    if (saved === "en" || saved === "fr") {
      // eslint-disable-next-line react-hooks/set-state-in-effect -- read once from storage after hydration
      setLangState(saved);
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);

  const value = useMemo<I18n>(() => {
    const d = DICTS[lang];
    return {
      lang,
      setLang,
      t: (key, vars) => fill(d[key] ?? en[key] ?? key, vars),
      tx: (key, fallback, vars) => {
        const s = (d as Record<string, string>)[key];
        return s !== undefined ? fill(s, vars) : fallback ?? key;
      },
    };
  }, [lang, setLang]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n outside I18nProvider");
  return v;
}
